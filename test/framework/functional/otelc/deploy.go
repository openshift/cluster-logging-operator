package otelc

import (
	"strings"

	log "github.com/ViaQ/logerr/v2/log/static"
	"github.com/openshift/cluster-logging-operator/internal/constants"
	"github.com/openshift/cluster-logging-operator/internal/runtime"
	"github.com/openshift/cluster-logging-operator/internal/utils"
	"github.com/openshift/cluster-logging-operator/test/client"
)

// ConfigFile is the key of the collector configuration in the config map and
// the file name the otel collector image loads from ConfigDir by default
const (
	ConfigFile = "config.yaml"
	ConfigDir  = "/etc/otel"
)

// OtelcCollector deploys the OpenTelemetry Collector as the collector under
// test. Its configuration is generated by the otelc generator framework
// (internal/generator/impl/otelc) via forwarder.GenerateFor.
type OtelcCollector struct {
	*client.Test
}

func (c *OtelcCollector) String() string {
	return constants.ComponentNameOtelc
}

func (c *OtelcCollector) DeployConfigMapForConfig(name, config, clfName, clfYaml string) error {
	log.V(2).Info("Creating config configmap")
	configmap := runtime.NewConfigMap(c.NS.Name, name, map[string]string{})
	runtime.NewConfigMapBuilder(configmap).
		Add(ConfigFile, config).
		Add("clfyaml", clfYaml)
	return c.Create(configmap)
}

func (c *OtelcCollector) BuildCollectorContainer(b *runtime.ContainerBuilder, nodeName string) *runtime.ContainerBuilder {
	// the image entrypoint loads ConfigDir/ConfigFile without further args,
	// the same convention the AddOTELCollector receiver container relies on.
	// Run as root like the vector image so the framework can write the fake
	// container logs under /var/log/pods inside this container
	return b.AddEnvVar("NODE_NAME", nodeName).
		AddRunAsUser(0).
		AddVolumeMount("config", ConfigDir, "", true)
}

func (c *OtelcCollector) IsStarted(logs string) bool {
	return strings.Contains(logs, "Everything is ready")
}

func (c *OtelcCollector) Image() string {
	return utils.GetComponentImage(constants.ComponentNameOtelc)
}

// ModifyConfig is a no-op: the otelc generator already emits the filelog
// receivers the functional framework writes to, so no source mocking is needed
func (c *OtelcCollector) ModifyConfig(conf string) string {
	return conf
}
