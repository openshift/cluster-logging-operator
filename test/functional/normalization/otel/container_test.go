package otel

import (
	"fmt"
	"time"

	"golang.org/x/exp/maps"

	. "github.com/onsi/ginkgo/v2"
	. "github.com/onsi/gomega"
	obs "github.com/openshift/cluster-logging-operator/api/observability/v1"
	"github.com/openshift/cluster-logging-operator/internal/constants"
	"github.com/openshift/cluster-logging-operator/internal/runtime"
	"github.com/openshift/cluster-logging-operator/internal/utils"
	"github.com/openshift/cluster-logging-operator/test/framework/functional"
	"github.com/openshift/cluster-logging-operator/test/helpers/types/otlp"
	obstestruntime "github.com/openshift/cluster-logging-operator/test/runtime/observability"
)

// Data model conformance for container logs written to an OTLP endpoint:
// https://github.com/rhobs/observability-data-model/blob/main/cluster-logging.md
//
// The test asserts the non-deprecated attributes defined by the data model are
// populated with the correct values. Deprecated ViaQ attributes (e.g.
// kubernetes.namespace_name, log_type) are intentionally not asserted: they are
// compatibility only and are not part of the data model.
var _ = Describe("[Functional][Normalization][OTLP] container logs conform to the Red Hat observability data model", func() {

	const (
		timestamp     = "2023-08-28T12:59:28.573159188+00:00"
		timestampNano = "1693227568573159188"
	)

	var (
		framework *functional.CollectorFunctionalFramework
		// the level=warn token is parsed by the viaq normalizer logfmt
		// level detection and drives SeverityText/SeverityNumber
		message = "level=warn normalize me to the observability data model"
	)

	var (
		openShiftLabels = map[string]string{"foo": "bar"}
	)

	BeforeEach(func() {
		// run the otelc collector (generated by the otelc generator framework)
		// as the collector under test; the receiver side is the otel collector
		// deployed by AddOTELCollector. Requires RELATED_IMAGE_OTEL_COLLECTOR
		// to be set in the environment.
		framework = functional.NewCollectorFunctionalFrameworkUsingCollector(constants.ComponentNameOtelc)
		framework.MaxReadDuration = utils.GetPtr(time.Second * 45)

		obstestruntime.NewClusterLogForwarderBuilder(framework.Forwarder).
			FromInput(obs.InputTypeApplication).
			WithLabelsFilter(openShiftLabels).
			ToOtlpOutput()

		Expect(framework.DeployWithVisitor(func(b *runtime.PodBuilder) error {
			return framework.AddOTELCollector(b, string(obs.OutputTypeOTLP))
		})).To(BeNil())
	})

	AfterEach(func() {
		framework.Cleanup()
	})

	It("should populate the data model resource and log record attributes for application container logs", func() {
		appNamespace := framework.Pod.Namespace

		crioLine := functional.NewCRIOLogMessage(timestamp, message, false)
		Expect(framework.WriteMessagesToNamespace(crioLine, appNamespace, 1)).To(Succeed())

		raw, err := framework.ReadRawApplicationLogsFrom(string(obs.OutputTypeOTLP))
		Expect(err).To(BeNil(), "Expected no errors reading the logs")
		Expect(raw).ToNot(BeEmpty())

		logs, err := otlp.ParseLogs(raw[0])
		Expect(err).To(BeNil(), "Expected no errors parsing the logs")

		resourceLogs := logs.ResourceLogs
		Expect(resourceLogs).To(HaveLen(1), "Expected a single ResourceLog")
		resource := resourceLogs[0].Resource

		By("asserting the required container resource attributes of the data model")
		expResourceAttributes := map[string]string{
			// openshift.* common attributes
			otlp.OpenshiftClusterUID: "", // any non-empty value
			otlp.OpenshiftLogSource:  string(obs.InfrastructureSourceContainer),
			otlp.OpenshiftLogType:    string(obs.InputTypeApplication),
			otlp.K8sNodeName:         "", // any non-empty value
			otlp.K8sNamespaceName:    appNamespace,
			otlp.K8sContainerName:    "", // any non-empty value
			otlp.K8sPodName:          framework.Pod.Name,
			otlp.K8sPodID:            string(framework.Pod.UID),
		}
		attributeNames := otlp.CollectNames(resource.Attributes)
		for name := range expResourceAttributes {
			Expect(attributeNames).To(ContainElement(name), "Expected resource to carry the data model attribute %s", name)
		}
		for name, expected := range expResourceAttributes {
			value := resource.Attribute(name).String()
			Expect(value).ToNot(BeEmpty(), "Expected data model attribute %s to have a value", name)
			if expected != "" {
				Expect(value).To(BeEquivalentTo(expected), "Expected data model attribute %s to match", name)
			}
		}

		By("asserting kubernetes and openshift labels are forwarded as resource attributes")
		for key, value := range framework.Pod.Labels {
			Expect(resource.Attribute(fmt.Sprintf("k8s.pod.label.%s", key)).String()).To(BeEquivalentTo(value),
				"Expected the kubernetes pod label %s to be forwarded", key)
		}
		for key, value := range openShiftLabels {
			Expect(resource.Attribute(otlp.OpenshiftLabelPrefix+key).String()).To(BeEquivalentTo(value),
				"Expected the openshift label %s to be forwarded", key)
		}

		By("asserting the resource carries no attributes outside the data model and its compatibility set")
		// The allowed set is the data model attributes, the forwarded pod and
		// openshift labels, and the deprecated ViaQ attributes. The otelc
		// collector must continue to emit the deprecated attributes for
		// compatibility until they are deliberately dropped; when that happens,
		// remove them from this allowlist so their reappearance fails the test.
		// Anything else appearing is a normalization bug.
		allowed := maps.Keys(expResourceAttributes)
		for key := range framework.Pod.Labels {
			allowed = append(allowed, fmt.Sprintf("k8s.pod.label.%s", key))
		}
		for key := range openShiftLabels {
			allowed = append(allowed, otlp.OpenshiftLabelPrefix+key)
		}
		allowed = append(allowed,
			// deprecated compatibility attributes
			otlp.LogSource,
			otlp.LogType,
			otlp.KubernetesContainerName,
			otlp.KubernetesHost,
			otlp.KubernetesPodName,
			otlp.KubernetesNamespaceName,
			otlp.OpenshiftClusterID,
		)
		Expect(attributeNames).To(ConsistOf(allowed),
			"Expected the resource attributes to be exactly the data model, label, and compatibility attributes")

		By("asserting the log record fields of the data model")
		scopeLogs := resourceLogs[0].ScopeLogs
		Expect(scopeLogs).To(HaveLen(1), "Expected a single scopeLog")
		logRecords := scopeLogs[0].LogRecords
		Expect(logRecords).To(HaveLen(1), "Expected a single log record")
		logRecord := logRecords[0]

		Expect(logRecord.Body.StringValue).To(Equal(message), "Expect the log body to carry the message")
		Expect(logRecord.TimeUnixNano).To(Equal(timestampNano), "Expect the timestamp to be converted into unix nano")
		Expect(logRecord.ObservedTimeUnixNano).To(MatchRegexp("[0-9]*"))
		// SeverityText is the original severity string from the source; the
		// viaq normalizer parsed "warn" from the logfmt level token
		Expect(logRecord.SeverityText).To(Equal("warn"), "Expect the severity text to carry the normalized level")
		// SeverityNumber is the OTel severity enum: the WARN band is 13-16
		// (WARN=13, WARN2=14, WARN3=15, WARN4=16)
		Expect(logRecord.SeverityNumber).To(BeNumerically(">=", 13), "Expect the severity number to be in the WARN band")
		Expect(logRecord.SeverityNumber).To(BeNumerically("<=", 16), "Expect the severity number to be in the WARN band")

		// the deprecated level attribute mirrors SeverityText
		Expect(logRecord.Attribute(otlp.Level).String()).To(Equal("warn"),
			"Expect the deprecated level attribute to mirror the severity text")
		Expect(logRecord.Attribute(otlp.LogIOStream).String()).To(Equal("stdout"),
			"Expect the log record to carry the data model log.iostream attribute")

		By("asserting the log record carries no attributes outside the data model and its compatibility set")
		Expect(otlp.CollectNames(logRecord.Attributes)).To(ConsistOf(
			otlp.LogIOStream,
			otlp.Level, // deprecated compatibility attribute
		), "Expected the log record attributes to be exactly the data model and compatibility attributes")
	})
})
